-- Reference DDL for PostgreSQL. NOT a substitute for reviewed Alembic migrations,
-- secret management, full authorization/RLS, vector extension/model-dimension migration,
-- application validation, retention or all phase-specific production constraints.
-- UUID columns receive UUIDv7 values supplied by BACKEND. No UUIDv4 defaults.

CREATE TABLE users (
    id uuid PRIMARY KEY,
    email text NOT NULL,
    password_hash text NOT NULL,
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active','disabled')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_users_email_normalized ON users (lower(email));

CREATE TABLE workspaces (
    id uuid PRIMARY KEY,
    slug text NOT NULL UNIQUE,
    display_name text NOT NULL,
    timezone text NOT NULL DEFAULT 'Asia/Ho_Chi_Minh',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE workspace_members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id uuid NOT NULL REFERENCES workspaces(id),
    user_id uuid NOT NULL REFERENCES users(id),
    role text NOT NULL CHECK (role IN ('owner','admin','member')),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (workspace_id, user_id)
);
CREATE INDEX ix_workspace_members_user ON workspace_members (user_id, workspace_id);

CREATE TABLE agents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id uuid NOT NULL UNIQUE,
    workspace_id uuid NOT NULL REFERENCES workspaces(id),
    name text NOT NULL,
    description text,
    draft_config jsonb NOT NULL DEFAULT '{}'::jsonb,
    published_revision_id bigint,
    state text NOT NULL DEFAULT 'draft' CHECK (state IN ('draft','published','paused','archived')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (id, workspace_id)
);
CREATE INDEX ix_agents_workspace ON agents(workspace_id, updated_at DESC, id DESC);
CREATE TABLE agent_revisions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id bigint NOT NULL REFERENCES agents(id),
    revision_no integer NOT NULL CHECK (revision_no > 0),
    config jsonb NOT NULL,
    published_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (agent_id, revision_no),
    UNIQUE (agent_id, id)
);
ALTER TABLE agents ADD CONSTRAINT fk_agents_published_revision
    FOREIGN KEY (id, published_revision_id) REFERENCES agent_revisions(agent_id, id);

CREATE TABLE products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id uuid NOT NULL REFERENCES workspaces(id),
    product_sku text,
    name text NOT NULL,
    description text,
    category text,
    price numeric(18, 2) CHECK (price IS NULL OR price >= 0),
    currency char(3) NOT NULL DEFAULT 'VND',
    product_url text,
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active','archived')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (id, workspace_id)
);
CREATE UNIQUE INDEX uq_products_workspace_sku ON products(workspace_id, product_sku) WHERE product_sku IS NOT NULL;
CREATE INDEX ix_products_workspace ON products(workspace_id, created_at DESC, id DESC);
CREATE TABLE product_variants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id uuid NOT NULL REFERENCES workspaces(id),
    product_id bigint NOT NULL,
    variant_sku text,
    name text,
    size text,
    color text,
    price_override numeric(18, 2) CHECK (price_override IS NULL OR price_override >= 0),
    stock_quantity integer CHECK (stock_quantity IS NULL OR stock_quantity >= 0),
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active','archived')),
    created_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (product_id, workspace_id) REFERENCES products(id, workspace_id)
);
CREATE UNIQUE INDEX uq_variants_workspace_sku ON product_variants(workspace_id, variant_sku) WHERE variant_sku IS NOT NULL;
CREATE INDEX ix_variants_product ON product_variants(workspace_id, product_id);

CREATE TABLE media_assets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id uuid NOT NULL REFERENCES workspaces(id),
    bucket text NOT NULL,
    object_key text NOT NULL UNIQUE,
    mime_type text NOT NULL,
    byte_size bigint NOT NULL CHECK (byte_size >= 0),
    sha256 text NOT NULL,
    visibility text NOT NULL CHECK (visibility IN ('private','public')),
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz,
    UNIQUE (id, workspace_id)
);
CREATE INDEX ix_media_workspace ON media_assets(workspace_id, id);
CREATE TABLE knowledge_documents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id uuid NOT NULL REFERENCES workspaces(id),
    asset_id bigint,
    title text NOT NULL,
    kind text NOT NULL CHECK (kind IN ('document','faq','policy','size_guide')),
    status text NOT NULL DEFAULT 'queued'
        CHECK (status IN ('queued','processing','ready','failed','deleted')),
    content_sha256 text,
    ingestion_error text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (id, workspace_id),
    FOREIGN KEY (asset_id, workspace_id) REFERENCES media_assets(id, workspace_id)
);
CREATE INDEX ix_documents_workspace_status ON knowledge_documents(workspace_id, status, id);
CREATE TABLE knowledge_chunks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id uuid NOT NULL,
    document_id bigint NOT NULL,
    position integer NOT NULL CHECK(position >= 0),
    content text NOT NULL,
    content_sha256 text NOT NULL,
    -- Add embedding vector(N) in a separate migration after the selected model is verified.
    UNIQUE(document_id, position),
    FOREIGN KEY (document_id, workspace_id) REFERENCES knowledge_documents(id, workspace_id)
);
CREATE INDEX ix_chunks_workspace_document ON knowledge_chunks(workspace_id, document_id, position);
CREATE TABLE ingestion_jobs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id uuid NOT NULL,
    document_id bigint NOT NULL,
    status text NOT NULL DEFAULT 'queued'
      CHECK (status IN ('queued','processing','succeeded','failed')),
    attempts integer NOT NULL DEFAULT 0,
    lease_until timestamptz,
    error text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (document_id, workspace_id) REFERENCES knowledge_documents(id, workspace_id)
);
CREATE INDEX ix_ingestion_claim ON ingestion_jobs(status, lease_until, id);

CREATE TABLE channels (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id uuid NOT NULL REFERENCES workspaces(id),
    provider text NOT NULL CHECK (provider IN ('web','facebook','zalo')),
    external_account_id text,
    state text NOT NULL DEFAULT 'disconnected' CHECK (state IN ('disconnected','connected','error')),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_channels_workspace ON channels(workspace_id, provider);
CREATE TABLE conversations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id uuid NOT NULL UNIQUE,
    workspace_id uuid NOT NULL REFERENCES workspaces(id),
    agent_id bigint NOT NULL,
    revision_id bigint,
    channel text NOT NULL DEFAULT 'web',
    anonymous_session_hash text,
    state text NOT NULL DEFAULT 'open' CHECK (state IN ('open','resolved')),
    started_at timestamptz NOT NULL DEFAULT now(),
    last_message_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(id, workspace_id),
    FOREIGN KEY (agent_id, workspace_id) REFERENCES agents(id, workspace_id),
    FOREIGN KEY (agent_id, revision_id) REFERENCES agent_revisions(agent_id, id)
);
CREATE INDEX ix_conversations_workspace_last ON conversations(workspace_id, last_message_at DESC, id DESC);
CREATE INDEX ix_conversations_agent ON conversations(agent_id, last_message_at DESC);
CREATE TABLE messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id uuid NOT NULL REFERENCES workspaces(id),
    conversation_id bigint NOT NULL,
    role text NOT NULL CHECK (role IN ('user','assistant','tool','system')),
    text_content text,
    attachments jsonb NOT NULL DEFAULT '[]'::jsonb,
    response_metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    client_message_key text,
    status text NOT NULL DEFAULT 'completed'
       CHECK (status IN ('pending','streaming','completed','failed','canceled')),
    created_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (conversation_id, workspace_id) REFERENCES conversations(id, workspace_id)
);
CREATE INDEX ix_messages_conversation ON messages(workspace_id, conversation_id, id);
CREATE UNIQUE INDEX uq_messages_idempotency ON messages(conversation_id, client_message_key)
    WHERE client_message_key IS NOT NULL;

CREATE TABLE auth_sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES users(id),
    refresh_token_hash text NOT NULL UNIQUE,
    family_key text NOT NULL,
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_sessions_user ON auth_sessions(user_id, expires_at DESC);
CREATE TABLE audit_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id uuid REFERENCES workspaces(id),
    actor_user_id uuid REFERENCES users(id),
    event_name text NOT NULL,
    target_ref text,
    safe_metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_audit_workspace_time ON audit_logs(workspace_id, created_at DESC);
